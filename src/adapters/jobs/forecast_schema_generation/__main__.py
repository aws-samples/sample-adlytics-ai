"""Generate contracts/generated/demand-forecast-boundaries.json from the boundary models.

`make generate-forecast-schemas` writes the file; `make check-forecast-schemas` regenerates and
fails on any diff, as `make check-tool-schemas` does for tools (design §4e). The file holds each
model's JSON Schema and its digest, the value the manifest, run report and run fingerprint carry.
Stdout is the interface: a command-line tool run by a make target.
"""

from __future__ import annotations

import json
import pathlib
import sys

from domain.forecasting.boundary import (
    BOUNDARY_MODELS,
    boundary_schema,
    boundary_schema_digest,
)

OUTPUT = pathlib.Path("contracts/generated/demand-forecast-boundaries.json")
CHECK_FLAG = "--check"


def render() -> str:
    """Build the file's contents deterministically (sorted keys, trailing newline)."""
    document = {
        "note": (
            "Generated by `make generate-forecast-schemas` from "
            "src/domain/forecasting/boundary.py. Do not edit."
        ),
        "schemas": {
            model.__name__: {
                "digest": boundary_schema_digest(model),
                "schema": boundary_schema(model),
            }
            for model in BOUNDARY_MODELS
        },
    }
    return json.dumps(document, indent=2, sort_keys=True) + "\n"


def main(argv: list[str]) -> int:
    """Write the artefact, or compare it and fail on a difference."""
    rendered = render()
    print("DEMAND FORECAST BOUNDARY SCHEMAS")
    print("=" * 60)
    for model in BOUNDARY_MODELS:
        print(f"  {model.__name__:<32} {boundary_schema_digest(model)}")
    if CHECK_FLAG in argv:
        if not OUTPUT.is_file() or OUTPUT.read_text() != rendered:
            print(f"\n{OUTPUT} is missing or stale. Run `make generate-forecast-schemas`.")
            return 1
        print(f"\n{OUTPUT} matches the boundary models.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered)
    print(f"\nwrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
