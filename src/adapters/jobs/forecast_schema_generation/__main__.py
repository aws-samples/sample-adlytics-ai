"""Generate the demand-forecast boundary schemas and the read API schema.

`contracts/generated/demand-forecast-boundaries.json` comes from the boundary models;
`contracts/generated/demand-forecast-api.json` from the read API models, routes and closed enums
(ADR-163). The API file carries no digest: no run fingerprint reads it.

`make generate-forecast-schemas` writes the file; `make check-forecast-schemas` regenerates and
fails on any diff, as `make check-tool-schemas` does for tools (design §4e). The file holds each
model's JSON Schema and its digest, the value the manifest, run report and run fingerprint carry.
Stdout is the interface: a command-line tool run by a make target.
"""

from __future__ import annotations

import json
import pathlib
import sys

from domain.forecasting.boundary import (
    BOUNDARY_MODELS,
    boundary_schema,
    boundary_schema_digest,
)
from domain.forecasting.read_api import API_ENUMS, API_MODELS, API_ROUTES

OUTPUT = pathlib.Path("contracts/generated/demand-forecast-boundaries.json")
API_OUTPUT = pathlib.Path("contracts/generated/demand-forecast-api.json")
CHECK_FLAG = "--check"


def render() -> str:
    """Build the file's contents deterministically (sorted keys, trailing newline)."""
    document = {
        "note": (
            "Generated by `make generate-forecast-schemas` from "
            "src/domain/forecasting/boundary.py. Do not edit."
        ),
        "schemas": {
            model.__name__: {
                "digest": boundary_schema_digest(model),
                "schema": boundary_schema(model),
            }
            for model in BOUNDARY_MODELS
        },
    }
    return json.dumps(document, indent=2, sort_keys=True) + "\n"


def render_api() -> str:
    """Build the read API file: each response model's schema, the routes and the enums."""
    document = {
        "note": (
            "Generated by `make generate-forecast-schemas` from "
            "src/domain/forecasting/read_api.py. Do not edit."
        ),
        "enums": {name: list(values) for name, values in API_ENUMS.items()},
        "routes": list(API_ROUTES),
        "schemas": {model.__name__: model.model_json_schema() for model in API_MODELS},
    }
    return json.dumps(document, indent=2, sort_keys=True) + "\n"


def main(argv: list[str]) -> int:
    """Write both artefacts, or compare them and fail on any difference."""
    outputs = ((OUTPUT, render()), (API_OUTPUT, render_api()))
    print("DEMAND FORECAST BOUNDARY SCHEMAS")
    print("=" * 60)
    for model in BOUNDARY_MODELS:
        print(f"  {model.__name__:<32} {boundary_schema_digest(model)}")
    print(f"  read API models: {', '.join(model.__name__ for model in API_MODELS)}")
    if CHECK_FLAG in argv:
        stale = [path for path, text in outputs if not path.is_file() or path.read_text() != text]
        for path in stale:
            print(f"\n{path} is missing or stale. Run `make generate-forecast-schemas`.")
        if stale:
            return 1
        print(f"\n{OUTPUT} and {API_OUTPUT} match the models.")
        return 0
    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"\nwrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
