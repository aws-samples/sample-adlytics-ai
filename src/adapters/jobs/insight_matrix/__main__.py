"""Generate and validate the committed insight deterministic-logic matrix.

The per-slot contracts in ``contracts/insights/*.yaml`` are the one source of truth for the
Gate-1 deterministic predicate (required evidence inputs, finding kinds, per-basis
materiality and near-zero prior bounds, silence condition) and the Gate-2 structured-output
declaration. This job projects them into a committed markdown matrix so the governance rules
are reviewable in the docs tree, and checks the committed projection against the contracts so
the two can never drift.
"""

from __future__ import annotations

import argparse
import pathlib
import sys
from typing import cast

import yaml

CONTRACTS_DIR = pathlib.Path("contracts/insights")
MATRIX_OUTPUT_PATH = pathlib.Path("docs/ui/generated/insight-deterministic-matrix.md")

_HEADER = """<!-- GENERATED by `make generate-insight-matrix` from contracts/insights/*.yaml.
     Do not edit: `make check-insight-matrix` fails on drift. The contracts are the one
     source of truth; this projection exists for docs-tree review visibility. -->

# Insight slot deterministic-logic matrix (generated)

Gate 1 runs server-side before any model call: deterministic findings are computed from the
served artifact's own numbers, then filtered by the slot contract's predicate — if nothing
survives, the slot is silent and no model is invoked. Gate 2 is structured generation: the model
receives only the surviving findings, must answer in the declared structured schema and output
class, and may choose silence. It may state the supplied values and figures validly derived from
them; figure faithfulness is judged by calibration and evaluation (ADR-082).

| Slot | Version | Output class | Deterministic findings | Required evidence inputs \
| Materiality (op / tac / pat) | Near-zero prior | Silence condition |
|---|---|---|---|---|---|---|---|
"""

_ROLES = ("operational-pulse", "tactical-review", "pattern-confirmation")


def _rows(rows: object) -> list[str]:
    declared = cast("dict[str, dict[str, object]]", rows or {})
    return [
        f"{name} {' / '.join(str(row[role]) for role in _ROLES)}" for name, row in declared.items()
    ]


def _materiality(materiality: dict[str, object]) -> str:
    """Render each basis's unit rows, then its per-metric rows, one basis per line."""
    bases = cast("dict[str, dict[str, object]]", materiality.get("bases") or {})
    lines = [
        f"`{basis}`: "
        + "; ".join(
            _rows(rows.get("per_unit")) + [f"`{row}`" for row in _rows(rows.get("per_metric"))]
        )
        for basis, rows in bases.items()
    ]
    return "<br>".join(lines) or "—"


def _near_zero(materiality: dict[str, object]) -> str:
    bounds = cast("dict[str, object]", materiality.get("near_zero_prior") or {})
    parts: list[str] = []
    for scale, bound in bounds.items():
        if isinstance(bound, dict):
            prices = cast("dict[str, object]", bound)
            parts.extend(f"{scale} `{metric}` {value}" for metric, value in prices.items())
        else:
            parts.append(f"{scale} {bound}")
    return "; ".join(parts) or "—"


def _row(document: dict[str, object]) -> str:
    predicate = cast("dict[str, object]", document.get("predicate") or {})
    materiality = cast("dict[str, object]", predicate.get("materiality") or {})
    findings = cast("list[object]", document.get("deterministic_findings") or [])
    inputs = cast("list[object]", predicate.get("required_evidence_inputs") or [])
    return (
        f"| `{document.get('id')}` "
        f"| {document.get('version')} "
        f"| {document.get('output_class')} "
        f"| {', '.join(str(v) for v in findings) or '—'} "
        f"| {', '.join(str(v) for v in inputs) or '—'} "
        f"| {_materiality(materiality)} "
        f"| {_near_zero(materiality)} "
        f"| {document.get('silence_condition', '—')} |\n"
    )


def render() -> str:
    """Project every insight contract into the one committed matrix, sorted by slot id."""
    rows: list[tuple[str, str]] = []
    for path in sorted(CONTRACTS_DIR.glob("*.yaml")):
        document = cast("dict[str, object]", yaml.safe_load(path.read_text()))
        rows.append((str(document.get("id")), _row(document)))
    body = "".join(row for _, row in sorted(rows))
    schema_note = (
        "\nEvery slot declares the same Gate-2 structured output schema"
        " (`insight-narration-v1`: `output_class`, `sentences`); a declared output"
        " class that differs from the slot's is rejected as malformed, and a narration's"
        " figures are judged by calibration and evaluation, never by a text check.\n"
    )
    return _HEADER + body + schema_note


def main() -> int:
    """Generate the committed matrix, or verify it byte-for-byte with ``--check``."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the committed projection")
    arguments = parser.parse_args()
    rendered = render()
    if arguments.check:
        committed = MATRIX_OUTPUT_PATH.read_text() if MATRIX_OUTPUT_PATH.exists() else ""
        if committed != rendered:
            sys.stderr.write(
                "insight matrix drift: run `make generate-insight-matrix` and commit.\n"
            )
            return 1
        sys.stdout.write("Insight deterministic matrix matches its contracts.\n")
        return 0
    MATRIX_OUTPUT_PATH.write_text(rendered)
    sys.stdout.write(f"wrote {MATRIX_OUTPUT_PATH}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
