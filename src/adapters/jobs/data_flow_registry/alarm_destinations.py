"""Generate and check the staffed alarm destination projections (S5, FR-10).

`contracts/operations/alarm-destinations.yaml` is the single source. This job validates the
`AlarmStaffingPolicy` and the destination arms, then renders a pure Python module and a
TypeScript module. It refuses to write either when a policy field is missing or blank, the policy
carries an undeclared field, or an environment selects an arm the contract does not declare, so a
stale or incomplete policy fails generation and synth. Revision 2 (owner-gate Item 20) retired the
acknowledgement fields.

    python -m adapters.jobs.data_flow_registry.alarm_destinations [--check]
"""

from __future__ import annotations

import hashlib
import json
import pprint
import sys
from pathlib import Path
from typing import Any, Final, cast

from adapters.outbound import repository_yaml

CONTRACT_PATH: Final = Path("contracts/operations/alarm-destinations.yaml")
PYTHON_PATH: Final = Path("src/domain/operations/generated_alarm_destinations.py")
TYPESCRIPT_PATH: Final = Path("infra/lib/generated/alarm-destinations.ts")
_CHECK: Final = "--check"
_POLICY_TEXT: Final = ("responsible_owner_id",)
_POLICY_NUMBERS: Final = ("policy_revision",)
_ARMS: Final = frozenset({"ExistingInAccountTopicEmail", "ExistingConfirmedSnsTopic"})


class AlarmDestinationContractError(ValueError):
    """The contract is malformed or its staffing policy is incomplete."""


def load_contract(root: Path) -> dict[str, Any]:
    """Read the contract and validate its closed shape."""
    document = repository_yaml.safe_load((root / CONTRACT_PATH).read_text())
    if not isinstance(document, dict):
        raise AlarmDestinationContractError("the alarm-destination contract is malformed.")
    contract = cast("dict[str, Any]", document)
    if contract.get("contract") != "alarm-destinations":
        raise AlarmDestinationContractError("the alarm-destination contract is malformed.")
    validate(contract)
    return contract


def validate(contract: dict[str, Any]) -> None:
    """Refuse a missing, blank or widened policy, and any undeclared arm."""
    policy = contract.get("staffing_policy")
    if not isinstance(policy, dict):
        raise AlarmDestinationContractError("the AlarmStaffingPolicy is missing.")
    fields = cast("dict[str, object]", policy)
    for name in _POLICY_TEXT:
        value = fields.get(name)
        if not isinstance(value, str) or not value.strip():
            raise AlarmDestinationContractError(f"the policy field {name} is missing or blank.")
    for name in _POLICY_NUMBERS:
        value = fields.get(name)
        if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
            raise AlarmDestinationContractError(f"the policy field {name} is not positive.")
    if set(fields) != {*_POLICY_TEXT, *_POLICY_NUMBERS}:
        raise AlarmDestinationContractError("the policy carries an undeclared field.")
    arms = contract.get("destination_arms")
    if not isinstance(arms, dict) or frozenset(cast("dict[str, object]", arms)) != _ARMS:
        raise AlarmDestinationContractError("the destination arms are not exactly the two arms.")
    selected = contract.get("selected_arms")
    if not isinstance(selected, dict) or not selected:
        raise AlarmDestinationContractError("no environment selects a destination arm.")
    for environment, arm in cast("dict[str, object]", selected).items():
        if arm not in _ARMS:
            raise AlarmDestinationContractError(f"{environment} selects an undeclared arm.")


def _frozen(value: object) -> object:
    if isinstance(value, list):
        return tuple(_frozen(item) for item in cast("list[object]", value))
    if isinstance(value, dict):
        return {key: _frozen(item) for key, item in cast("dict[str, object]", value).items()}
    return value


def render_python(contract: dict[str, Any], digest: str) -> str:
    """Render the deterministic pure-Python projection."""
    constants: list[tuple[str, object]] = [
        ("CONTRACT_REVISION", contract["contract_revision"]),
        ("CONTRACT_DIGEST", digest),
        ("STAFFING_POLICY", contract["staffing_policy"]),
        ("DESTINATION_ARMS", contract["destination_arms"]),
        ("SELECTED_ARMS", contract["selected_arms"]),
    ]
    lines = [
        "# SPDX-License-Identifier: MIT-0",
        '"""Generated by `make generate-alarm-destinations`; do not edit by hand."""',
        "",
        "from typing import Any, Final",
        "",
    ]
    for name, value in constants:
        if isinstance(value, str | int | bool):
            lines.append(f"{name}: Final = {value!r}")
        else:
            rendered = pprint.pformat(_frozen(value), width=92, sort_dicts=False)
            lines.append(f"{name}: Final[Any] = (\n{rendered}\n)")
    return "\n".join(lines) + "\n"


def render_typescript(contract: dict[str, Any], digest: str) -> str:
    """Render the infrastructure projection: the policy, the arms and each selection."""
    values: dict[str, object] = {
        "ALARM_DESTINATION_CONTRACT_DIGEST": digest,
        "STAFFING_POLICY": contract["staffing_policy"],
        "DESTINATION_ARMS": sorted(contract["destination_arms"]),
        "SELECTED_ARMS": contract["selected_arms"],
    }
    lines = [
        "// SPDX-License-Identifier: MIT-0",
        "// Generated by `make generate-alarm-destinations`; do not edit by hand.",
    ]
    for name, value in values.items():
        lines.append(f"export const {name} = {json.dumps(value, sort_keys=True)} as const;")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write both projections, or check that they are current and the policy is complete."""
    arguments = sys.argv[1:] if argv is None else argv
    if any(argument != _CHECK for argument in arguments):
        sys.stderr.write(
            "usage: python -m adapters.jobs.data_flow_registry.alarm_destinations [--check]\n"
        )
        return 2
    root = Path.cwd()
    try:
        contract = load_contract(root)
    except (AlarmDestinationContractError, ValueError) as error:
        sys.stderr.write(f"ALARM DESTINATION CONTRACT ERROR: {error}\n")
        return 1
    digest = hashlib.sha256((root / CONTRACT_PATH).read_bytes()).hexdigest()
    rendered = {
        PYTHON_PATH: render_python(contract, digest),
        TYPESCRIPT_PATH: render_typescript(contract, digest),
    }
    if _CHECK in arguments:
        stale = [
            f"{path} is missing or stale; run make generate-alarm-destinations"
            for path, text in rendered.items()
            if not (root / path).is_file() or (root / path).read_text() != text
        ]
        if stale:
            sys.stderr.write("ALARM DESTINATION CHECK FAILED\n")
            for finding in stale:
                sys.stderr.write(f"  {finding}\n")
            return 1
        sys.stdout.write("ALARM DESTINATION CHECK PASSED: staffing policy complete.\n")
        return 0
    for path, text in rendered.items():
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        (root / path).write_text(text)
        sys.stdout.write(f"wrote {path}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
