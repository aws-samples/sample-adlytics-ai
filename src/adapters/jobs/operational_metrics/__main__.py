"""Generate and check the operational-metric projections (demand-forecast design §9).

The `operational_metrics` section of `contracts/shared/metric-dictionary.yaml` is the single
declaration of every CloudWatch metric the forecast and the Vendor Central producer emit. CDK can't
parse YAML without a new dependency, so this job projects the section the way
`adapters.jobs.data_flow_registry.alarm_destinations` projects its contract: a pure Python module
for the emitters, a TypeScript module for the alarms, and a Python module for the connector, which
holds only the producer namespace. Each carries the section's digest, so `--check` fails a stale
projection and emitters and alarms cannot drift apart.

    python -m adapters.jobs.operational_metrics [--check]

Stdout is the interface: a command-line tool run by a make target.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Final

from adapters.outbound.metric_dictionary import OperationalMetric, load_operational_metrics
from domain.catalog.capability import CatalogError

PYTHON_PATH: Final = Path("src/domain/operations/generated_operational_metrics.py")
TYPESCRIPT_PATH: Final = Path("infra/lib/generated/operational-metrics.ts")
CONNECTOR_PATH: Final = Path("connectors/vendor_central/generated_metrics.py")
CONNECTOR_NAMESPACE: Final = "Adlytics/VendorProducer"
"""The producer account's namespace; the connector's projection holds only its metrics."""
_CHECK: Final = "--check"
_PASCAL_NAME: Final = re.compile(r"[A-Z][A-Za-z0-9]*")
_DIGEST_PRAGMA: Final = "pragma: allowlist nextline secret (A-ENTROPY-IDENTIFIER-001)"


class OperationalMetricProjectionError(ValueError):
    """A declared metric name can't be projected to a constant."""


def section_digest(metrics: tuple[OperationalMetric, ...]) -> str:
    """SHA-256 of the section's canonical JSON, in declared order, every field included."""
    document = [
        {
            "namespace": metric.namespace,
            "name": metric.name,
            "unit": metric.unit,
            "statistic": metric.statistic,
            "dimensions": [[name, list(values)] for name, values in metric.dimensions],
            "meaning": metric.meaning,
        }
        for metric in metrics
    ]
    canonical = json.dumps(document, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(canonical.encode()).hexdigest()


def constant_name(metric_name: str) -> str:
    """`ForecastRunOutcome` → `FORECAST_RUN_OUTCOME`; refuse a name that isn't PascalCase."""
    if not _PASCAL_NAME.fullmatch(metric_name):
        raise OperationalMetricProjectionError(
            f"operational metric {metric_name!r} is not a PascalCase name."
        )
    return re.sub(r"(?<!^)(?=[A-Z])", "_", metric_name).upper()


def _text(value: str) -> str:
    """Quote as `ruff format` does, so the projection is already formatted."""
    return json.dumps(value)


def _python_spec(metric: OperationalMetric) -> list[str]:
    lines = [
        f"{constant_name(metric.name)}: Final = OperationalMetricSpec(",
        f"    namespace={_text(metric.namespace)},",
        f"    name={_text(metric.name)},",
        f"    unit={_text(metric.unit)},",
        f"    statistic={_text(metric.statistic)},",
    ]
    if not metric.dimensions:
        lines.append("    dimensions=(),")
    else:
        lines.append("    dimensions=(")
        for name, values in metric.dimensions:
            lines.extend(["        (", f"            {_text(name)},", "            ("])
            lines.extend(f"                {_text(value)}," for value in values)
            lines.extend(["            ),", "        ),"])
        lines.append("    ),")
    lines.append(")")
    return lines


def _render_python_module(
    metrics: tuple[OperationalMetric, ...], digest: str, audience: str
) -> str:
    lines = [
        "# SPDX-License-Identifier: MIT-0",
        '"""Generated by `make generate-operational-metrics`; do not edit by hand.',
        "",
        "The `operational_metrics` section of contracts/shared/metric-dictionary.yaml,",
        f"projected for {audience}.",
        '"""',
        "",
        "from dataclasses import dataclass",
        "from typing import Final",
        "",
        "",
        "@dataclass(frozen=True, slots=True)",
        "class OperationalMetricSpec:",
        '    """One declared CloudWatch metric and every dimension value it may carry."""',
        "",
        "    namespace: str",
        "    name: str",
        "    unit: str",
        "    statistic: str",
        "    dimensions: tuple[tuple[str, tuple[str, ...]], ...]",
        "",
        "",
        f"# {_DIGEST_PRAGMA}",
        f"SECTION_DIGEST: Final = {_text(digest)}",
        "",
    ]
    for metric in metrics:
        lines.extend(_python_spec(metric))
        lines.append("")
    names = [constant_name(metric.name) for metric in metrics]
    if len(names) > 1:
        lines.append("OPERATIONAL_METRICS: Final = (")
        lines.extend(f"    {name}," for name in names)
        lines.append(")")
    else:
        # `ruff format` keeps a one-element tuple on one line: its comma is not a magic one.
        lines.append(f"OPERATIONAL_METRICS: Final = ({''.join(f'{name},' for name in names)})")
    return "\n".join(lines) + "\n"


def render_python(metrics: tuple[OperationalMetric, ...], digest: str) -> str:
    """Render the emitters' projection: every declared metric, both namespaces."""
    return _render_python_module(metrics, digest, "the Adlytics emitters")


def render_connector(metrics: tuple[OperationalMetric, ...], digest: str) -> str:
    """Render the connector's projection: its namespace only, the whole section's digest."""
    own = tuple(metric for metric in metrics if metric.namespace == CONNECTOR_NAMESPACE)
    return _render_python_module(
        own, digest, f"the Vendor Central connector ({CONNECTOR_NAMESPACE})"
    )


def render_typescript(metrics: tuple[OperationalMetric, ...], digest: str) -> str:
    """Render the alarms' projection: metrics keyed by name, dimensions to allowed values."""
    declared = {
        metric.name: {
            "namespace": metric.namespace,
            "name": metric.name,
            "unit": metric.unit,
            "statistic": metric.statistic,
            "dimensions": {name: list(values) for name, values in metric.dimensions},
        }
        for metric in metrics
    }
    lines = [
        "// SPDX-License-Identifier: MIT-0",
        "// Generated by `make generate-operational-metrics`; do not edit by hand.",
        f"// {_DIGEST_PRAGMA}",
        f"export const OPERATIONAL_METRICS_DIGEST = {json.dumps(digest)} as const;",
        f"export const OPERATIONAL_METRICS = {json.dumps(declared, indent=2)} as const;",
    ]
    return "\n".join(lines) + "\n"


def render(metrics: tuple[OperationalMetric, ...]) -> dict[Path, str]:
    """Every projection's path and text, each carrying the section's digest."""
    digest = section_digest(metrics)
    return {
        PYTHON_PATH: render_python(metrics, digest),
        TYPESCRIPT_PATH: render_typescript(metrics, digest),
        CONNECTOR_PATH: render_connector(metrics, digest),
    }


def main(argv: list[str] | None = None) -> int:
    """Write the three projections, or check that each is current."""
    arguments = sys.argv[1:] if argv is None else argv
    if any(argument != _CHECK for argument in arguments):
        sys.stderr.write("usage: python -m adapters.jobs.operational_metrics [--check]\n")
        return 2
    root = Path.cwd()
    try:
        rendered = render(load_operational_metrics(root))
    except (CatalogError, OperationalMetricProjectionError) as error:
        sys.stderr.write(f"OPERATIONAL METRICS ERROR: {error}\n")
        return 1
    if _CHECK in arguments:
        stale = [
            f"{path} is missing or stale; run make generate-operational-metrics"
            for path, text in rendered.items()
            if not (root / path).is_file() or (root / path).read_text() != text
        ]
        if stale:
            sys.stderr.write("OPERATIONAL METRICS CHECK FAILED\n")
            for finding in stale:
                sys.stderr.write(f"  {finding}\n")
            return 1
        sys.stdout.write("OPERATIONAL METRICS CHECK PASSED: every projection is current.\n")
        return 0
    for path, text in rendered.items():
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        (root / path).write_text(text)
        sys.stdout.write(f"wrote {path}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
