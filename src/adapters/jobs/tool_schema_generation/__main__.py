"""Generate the Gateway tool definitions from the tool contracts.

`make generate-tool-schemas` writes the file; `make check-tool-schemas` regenerates and fails on
any diff. That pairing is what makes it impossible for a tool's input schema to exist in two
places — the same guarantee `make check-schemas` gives the curated table definitions, and for the
same reason: a hand-written copy beside a declaration is a second source of truth, and the two
drift silently because each looks internally correct.

Output is JSON because the consumer is CDK. `AgentStack` reads this file and builds one Gateway
target per tool from it.

**What this gate cannot check.** It proves the generated file matches the declaration. It cannot
prove the declaration matches what a handler actually dereferences — a schema declaring
`windowStart` beside a handler reading `window_start` would regenerate clean and refuse every call.
That direction is covered by tests which build an event from each declaration and drive the real
handler with it.

Stdout is the interface, the same as the contract gate: this is a command-line tool run by a make
target, not a service.
"""

from __future__ import annotations

import json
import pathlib
import sys

from adapters.inbound.tool_handlers.schemas import TOOL_CONTRACTS, as_tool_definitions

OUTPUT = pathlib.Path("contracts/generated/tools.json")

CHECK_FLAG = "--check"


def render() -> str:
    """Build the file's contents, deterministically.

    Sorted keys and a trailing newline so the staleness check compares content rather than
    formatting, and so a regenerated file produces no diff on a machine with a different dict
    ordering.
    """
    document = {
        "note": (
            "Generated by `make generate-tool-schemas` from "
            "src/adapters/inbound/tool_handlers/schemas.py. Do not edit."
        ),
        "tools": as_tool_definitions(),
    }
    return json.dumps(document, indent=2, sort_keys=True) + "\n"


def main(argv: list[str]) -> int:
    """Write the artefact, or compare it and fail on a difference."""
    checking = CHECK_FLAG in argv
    rendered = render()

    print("TOOL SCHEMA GENERATION")
    print("=" * 60)
    print(f"  contracts: {len(TOOL_CONTRACTS)}")
    for contract in TOOL_CONTRACTS:
        required = ", ".join(contract.required) or "none"
        print(f"    {contract.name:<32} required: {required}")

    if checking:
        if not OUTPUT.is_file():
            print(f"\n{OUTPUT} is missing. Run `make generate-tool-schemas`.")
            return 1
        if OUTPUT.read_text() != rendered:
            print(
                f"\n{OUTPUT} is stale against the tool contracts.\n"
                "Run `make generate-tool-schemas` and commit the result."
            )
            return 1
        print(f"\n{OUTPUT} matches the tool contracts.")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered)
    print(f"\nwrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
