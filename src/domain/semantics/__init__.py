"""Semantic Architecture V2 value objects.

Pure domain. This package states the meanings that have to survive every adapter boundary:
physical delivery identity, analytical identity, source revision, measurement time, and metric
compatibility. It reads no contract file and touches no store; adapters load declarations into these
types, then the domain decides whether the declaration is coherent.

Source-pack and query-pack formats deliberately do not live here. They are later enablement layers
that compile into this vocabulary rather than extending it with strings the planner does not know.
"""

